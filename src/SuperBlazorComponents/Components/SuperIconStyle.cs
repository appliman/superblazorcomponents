    /// </summary>
    Solid,

    /// <summary>
    /// Icône régulière (fa-regular).
    /// </summary>
    Regular,

    /// <summary>
    /// Icône de marque (fa-brands).
    /// </summary>
    Brands,

    /// <summary>
    /// Icône duotone (fa-duotone).
    /// </summary>
    Duotone
}
